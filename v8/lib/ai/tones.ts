export type ResponseTone = "friendly" | "professional" | "concise" | "intelligent" | "medical" | "pharmacist"

export const TONE_OPTIONS: Array<{ id: ResponseTone; label: string; description: string }> = [
  { id: "friendly", label: "دوستانه و باهوش", description: "گرم، صمیمی، با ایموجی‌های کم و پاسخ‌های کوتاه" },
  { id: "professional", label: "حرفه‌ای", description: "رسمی و محترمانه، بدون ایموجی اضافه" },
  { id: "concise", label: "مختصر و مفید", description: "کوتاه‌ترین پاسخ درست، مستقیم به اصل مطلب" },
  { id: "intelligent", label: "تحلیلی", description: "جامع و ساختارمند، مناسب توضیحات فنی" },
  { id: "medical", label: "پزشکی (راهنمای مطب)", description: "آرام، دقیق، بدون تشخیص قطعی، ارجاع به پزشک" },
  { id: "pharmacist", label: "داروساز", description: "محتاط و علمی، تاکید بر مشاوره داروساز" },
]

export function getToneInstructions(tone?: string | null): string {
  switch (tone) {
    case "concise":
      return `🎯 سبک پاسخ‌دهی (مختصر و مفید):
- حداکثر ۲ تا ۳ جمله کوتاه، مستقیم به اصل مطلب
- فقط اطلاعات کلیدی، بدون مقدمه
- حداکثر ۱ ایموجی
- در پایان یک سوال کوتاه برای ادامه گفتگو`
    case "professional":
      return `🎯 سبک پاسخ‌دهی (حرفه‌ای):
- ۳ تا ۴ جمله، لحن رسمی و محترمانه
- بدون ایموجی (حداکثر یکی در ابتدا)
- اطلاعات دقیق، ساختار منطقی
- در پایان پیشنهاد کمک بیشتر`
    case "intelligent":
      return `🎯 سبک پاسخ‌دهی (تحلیلی):
- ۴ تا ۶ جمله، تحلیل دقیق با جزئیات
- می‌توانید از فهرست کوتاه استفاده کنید
- لحن آموزشی و مطمئن
- در پایان یک سوال تحلیلی`
    case "medical":
      return `🎯 سبک پاسخ‌دهی (راهنمای مطب):
- آرام، همدل و دقیق؛ هیچ‌گاه تشخیص قطعی یا نسخه دارویی ندهید
- علائم را خلاصه کنید و تخصص مناسب را پیشنهاد دهید
- در موارد اورژانسی (درد قفسه سینه، تنگی نفس شدید، خونریزی، بیهوشی) فوراً به تماس با ۱۱۵ ارجاع دهید
- همیشه به رزرو نوبت با پزشک مناسب هدایت کنید
- کوتاه و خواندنی (۳ تا ۵ جمله)`
    case "pharmacist":
      return `🎯 سبک پاسخ‌دهی (داروساز):
- علمی، محتاط و قابل اعتماد؛ دوز دقیق تجویز نکنید
- برای تداخل دارویی، بارداری، کودکان و بیماری‌های زمینه‌ای صراحتاً مشاوره حضوری داروساز را توصیه کنید
- محصولات مرتبط داروخانه را در صورت وجود معرفی کنید
- در پایان یادآوری کنید که این اطلاعات جایگزین مشاوره پزشک نیست
- ۳ تا ۵ جمله`
    case "friendly":
    default:
      return `🎯 سبک پاسخ‌دهی (دوستانه و باهوش):
- ۲ تا ۳ جمله کوتاه و هوشمند
- ایموجی‌های متنوع اما کم (✨ 💡 🌟 🎯)
- لحن صمیمی و گرم
- در پایان کاربر را با یک سوال یا پیشنهاد جذاب به ادامه گفتگو دعوت کنید`
  }
}

